package com.example.qqbot.qa;

import java.util.Set;

/**
 * 关键词过滤器：把「太泛」的词挡掉。

 * <h2>什么是「泛词」</h2>
 * 群友问「这把剑的伤害怎么算」，关键词抽取会命中术语表里的「武器」——
 * 但**点「武器」会看到 970 条，等于没筛选**。

 * <p>对比：「卷毛山羊」点进去就一个东西。这才是「快速跳转」该有的效果。

 * <h2>为什么在展示层过滤</h2>
 * 抽取时就把泛词丢掉的话，历史数据里的泛词还在（已经入库了）。
 * 在展示层过滤的好处：
 * <ul>
 *   <li>不动历史数据</li>
 *   <li>停用词表可以随时调，改完立即生效</li>
 *   <li>万一以后想放开某个词，删一行就行</li>
 * </ul>
 */
public final class KeywordFilter {

    private KeywordFilter() {
    }

    /**
     * 泛词表。
     *
     * <p>分四类：
     * <ol>
     *   <li><b>大类名</b> —— 装备、武器、材料…（点进去等于没点）</li>
     *   <li><b>游戏元词</b> —— 游戏名、玩法、系统…（太大）</li>
     *   <li><b>操作词</b> —— 制作、强化、升级…（是动作不是东西）</li>
     *   <li><b>噪音</b> —— 欢迎、谢谢、测试…（不是查询）</li>
     * </ol>
     */
    private static final Set<String> STOP = Set.of(
            // ① 大类名
            "装备", "武器", "防具", "护甲", "工具", "材料", "资源",
            "消耗品", "食物", "药水", "宝石", "饰品", "道具", "物品",
            "建筑", "家具", "装饰", "染料", "种子", "幼苗", "花盆",
            "怪物", "敌人", "生物", "动物", "植物", "地点", "地图", "区域",
            "任务", "技能", "成就", "天赋", "法术", "魔法",
            // ② 游戏元词
            "雾锁王国", "游戏", "玩法", "系统", "界面", "菜单", "设置",
            "版本", "更新", "补丁", "攻略", "资料", "内容", "数据",
            "属性", "数值", "面板", "状态", "效果", "机制",
            // ③ 操作词
            "制作", "合成", "强化", "升级", "解锁", "获得", "获取", "收集",
            "建造", "修复", "拆除", "交易", "购买", "出售", "使用", "装备上",
            // ④ 噪音
            "欢迎", "谢谢", "感谢", "你好", "测试", "试试", "什么", "怎么",
            "哪里", "哪里能", "如何", "为什么", "可以", "能不能", "有没有",
            "这个东西", "那个东西", "大佬", "求助", "帮忙"
    );

    /**
     * 这个词该不该作为「热词」展示？
     *
     * @return true = 太泛/是噪音，应该过滤掉
     */
    public static boolean isTooGeneric(String keyword) {
        if (keyword == null || keyword.isBlank()) {
            return true;
        }
        String k = keyword.trim();
        if (STOP.contains(k)) {
            return true;
        }
        // 只有 1 个字的词基本没信息量（如「剑」「弓」）—— 但它可能是有效简称，
        // 所以只挡纯功能字
        if (k.length() == 1) {
            return "的了在是有和与都不很".indexOf(k.charAt(0)) >= 0;
        }
        return false;
    }

    /** 停用词数量（诊断用） */
    public static int size() {
        return STOP.size();
    }
}
