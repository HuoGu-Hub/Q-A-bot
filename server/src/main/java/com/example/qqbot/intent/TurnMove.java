package com.example.qqbot.intent;

/**
 * 这一轮用户想要什么 —— <b>只用于决定"给模型看什么"，不决定"模型怎么写"</b>。
 *
 * <p>三个取值会真的改变行为（{@link #SOCIAL} / {@link #META} / {@link #OUT_OF_SCOPE}
 * 不检索），{@link #CORRECT} 会在后面几轮接上"只改被指出的那一点"。
 * 其余取值目前只是记账，让日志能统计出真实分布。
 *
 * <h2>为什么没有"建议类"</h2>
 * 规则判"这是不是要我给建议"误伤太高（实测："你说一下长守镇的主人是谁"会被"主人"打成社交）。
 * 建议类只影响怎么写，不影响查不查，所以交给 {@code system.md} 的契约，这里不判。
 */
public enum TurnMove {

    /** 事实查询：是什么、在哪、怎么获得、多少级 */
    FACT,

    /** 建议、搭配、评价 —— 目前不单独识别，留作记账 */
    ADVISE,

    /** 社交：卖萌、撒娇、开玩笑、骂人 */
    SOCIAL,

    /** 关于 bot 自己：你是谁、什么模型、有什么能力 */
    META,

    /** 做不到的请求：帮忙上班、生成图片、下单 */
    OUT_OF_SCOPE,

    /** 对上一轮回答的纠正 */
    CORRECT,

    /** 没识别出别的，走现有链路 */
    DEFAULT
}
